/** Setups workspace: the aero map, CFD import and wing-angle sweeps. */
import { useMemo, useState } from "react";
import { Callout, Card } from "../components/Card";
import { ChartCard, extent, linspace, XYChart, type Marker, type Series } from "../components/Charts";
import { Legend, NumberField, Segmented } from "../components/Controls";
import { IconAlert, IconInfo, IconPlus } from "../components/Icons";
import {
  convergedCoefficients,
  criticalRadius,
  downforceFactor,
  efficiency,
  evaluateCorner,
  guessColumns,
  readForceHistory,
  readWingSweep,
  sweepAt,
  type AeroSetup,
} from "../engine";
import { fmt, fmtUnit } from "../format";
import { useApp } from "../state";
import { SetupName, WsHeader } from "./common";

/** Deterministic synthetic force history used only to demonstrate the importer. */
function exampleForceCoeffs(): string {
  const lines = [
    "# Synthetic example generated by VDPM-RaceTwin to demonstrate the importer. Not CFD output.",
    "# Aref : 1.5",
    "# Time Cd Cs Cl CmRoll CmPitch CmYaw",
  ];
  for (let i = 1; i <= 1500; i++) {
    const cd = 0.94 + 0.42 * Math.exp(-i / 170) + 0.004 * Math.sin(i / 9);
    const cl = -(3.05 - 1.3 * Math.exp(-i / 210)) + 0.012 * Math.sin(i / 7 + 1);
    lines.push(`${i} ${cd.toFixed(6)} 0 ${cl.toFixed(6)} 0 0 0`);
  }
  return lines.join("\n");
}

const EXAMPLE_SWEEP = [
  "angle_deg,C_D,C_DF",
  ...linspace(0, 20, 9).map((a) => `${a},${(0.7 + 0.0011 * a * a + 0.004 * a).toFixed(4)},${(1.9 + 0.13 * a - 0.0014 * a * a).toFixed(4)}`),
].join("\n");

export function Setups() {
  const { state, dispatch, derived, theme } = useApp();
  const { colours } = derived;
  const full = state.setups.length >= 8;
  const speed = 30;

  // ------------------------------------------------------------- aero map
  const cds = state.setups.map((s) => s.dragCoefficient);
  const cdfs = state.setups.map((s) => s.downforceCoefficient);
  const xDom = extent([...cds, 0.5, 1.3], 0.08);
  const yDom = extent([...cdfs, 1.5, 4], 0.1);
  const isoEff = [2, 2.5, 3, 3.5, 4].filter((e) => e * xDom[0] < yDom[1] && e * xDom[1] > yDom[0]);
  const isoSeries: Series[] = isoEff.map((e) => {
    const x0 = Math.max(xDom[0], yDom[0] / e);
    const x1 = Math.min(xDom[1], yDom[1] / e);
    return {
      id: `e${e}`,
      label: `C_DF / C_D = ${e}`,
      colour: theme.faint,
      dashed: true,
      width: 1,
      endLabel: `${e}`,
      points: linspace(x0, x1, 2).map((x) => [x, e * x] as [number, number]),
    };
  });
  const markers: Marker[] = state.setups.map((s) => ({ x: s.dragCoefficient, y: s.downforceCoefficient, colour: colours[s.name] ?? theme.ink, label: s.name }));

  // ------------------------------------------------------------- CFD import
  const [cfdText, setCfdText] = useState("");
  const [cfdName, setCfdName] = useState("CFD case");
  const [windowPct, setWindowPct] = useState(10);
  const [liftSign, setLiftSign] = useState<"-1" | "1">("-1");
  const [cols, setCols] = useState<{ drag: string; lift: string } | null>(null);
  const parsed = useMemo(() => {
    if (!cfdText.trim()) return null;
    try {
      const h = readForceHistory(cfdText);
      const g = guessColumns(h);
      return { h, guess: g, error: null as string | null };
    } catch (e) {
      return { h: null, guess: null, error: (e as Error).message };
    }
  }, [cfdText]);
  const dragCol = cols?.drag ?? parsed?.guess?.drag ?? null;
  const liftCol = cols?.lift ?? parsed?.guess?.lift ?? null;
  const converged = useMemo(() => {
    if (!parsed?.h || !dragCol || !liftCol) return null;
    try {
      return convergedCoefficients(parsed.h, dragCol, liftCol, windowPct / 100, Number(liftSign) as 1 | -1);
    } catch {
      return null;
    }
  }, [parsed, dragCol, liftCol, windowPct, liftSign]);

  const historySeries: Series[] = [];
  let historyBand: [number, number] | null = null;
  if (parsed?.h && dragCol && liftCol) {
    const idx = parsed.h.index;
    const stride = Math.max(1, Math.floor(idx.length / 600));
    const pick = <T,>(arr: T[]) => arr.filter((_, i) => i % stride === 0 || i === arr.length - 1);
    historySeries.push({ id: "cd", label: "C_D", colour: colours[state.setups[0]?.name ?? ""] ?? theme.ink, points: pick(idx.map((x, i) => [x, parsed.h!.columns[dragCol]![i]!] as [number, number])) });
    historySeries.push({ id: "cdf", label: "C_DF", colour: colours[state.setups[1]?.name ?? ""] ?? theme.muted, points: pick(idx.map((x, i) => [x, Number(liftSign) * parsed.h!.columns[liftCol]![i]!] as [number, number])) });
    const n = Math.max(1, Math.round(idx.length * (windowPct / 100)));
    historyBand = [idx[idx.length - n]!, idx[idx.length - 1]!];
  }
  const historyY = extent(historySeries.flatMap((s) => s.points.map((p) => p[1])), 0.08, true);
  const drifting = converged && (converged.dragDrift > 0.01 || converged.downforceDrift > 0.01);

  // ------------------------------------------------------------- wing sweep
  const [sweepText, setSweepText] = useState("");
  const [angle, setAngle] = useState(10);
  const sweep = useMemo(() => {
    if (!sweepText.trim()) return { s: null, error: null as string | null };
    try {
      return { s: readWingSweep(sweepText), error: null };
    } catch (e) {
      return { s: null, error: (e as Error).message };
    }
  }, [sweepText]);
  const sw = sweep.s;
  const swRange: [number, number] = sw ? [sw.angles[0]!, sw.angles[sw.angles.length - 1]!] : [0, 1];
  const swAngle = Math.min(Math.max(angle, swRange[0]), swRange[1]);
  const swAt = sw ? sweepAt(sw, swAngle) : null;

  const add = (setup: AeroSetup) => dispatch({ type: "addSetup", setup });

  return (
    <div className="workspace">
      <WsHeader
        title="Setups"
        lead="The aerodynamic configurations under comparison. Add setups from CFD force histories or from a measured wing-angle sweep; edit them in the sidebar."
      />

      <div className="grid grid-main-side">
        <Card title="Setup data" subtitle={`Forces at the case-study speed v = ${speed} m/s with the vehicle and air density in the sidebar.`}>
          <div className="table-wrap">
            <table className="data">
              <thead>
                <tr>
                  <th>Setup</th>
                  <th className="num">C_D</th>
                  <th className="num">C_DF</th>
                  <th className="num">C_DF / C_D</th>
                  <th className="num">Drag</th>
                  <th className="num">Downforce</th>
                  <th className="num" title="Radius beyond which the setup has no grip-limited speed">r*</th>
                  <th>Source</th>
                </tr>
              </thead>
              <tbody>
                {state.setups.map((s) => {
                  const r = evaluateCorner(state.vehicle, s, speed, 60, state.env);
                  const rStar = criticalRadius(state.vehicle.mass, state.vehicle.friction, downforceFactor(state.env.airDensity, s.downforceCoefficient, state.vehicle.referenceArea));
                  return (
                    <tr key={s.name}>
                      <td>
                        <SetupName name={s.name} colour={colours[s.name]} bold />
                        {s.description && <div className="faint" style={{ fontSize: 12, marginLeft: 18 }}>{s.description}</div>}
                      </td>
                      <td className="num">{fmt(s.dragCoefficient, 3)}</td>
                      <td className="num">{fmt(s.downforceCoefficient, 3)}</td>
                      <td className="num">{fmt(efficiency(s), 2)}</td>
                      <td className="num">{fmt(r.drag, 1)} N</td>
                      <td className="num">{fmt(r.downforce, 1)} N</td>
                      <td className="num">{fmtUnit(rStar, "m", 0)}</td>
                      <td className="muted" style={{ fontSize: 12 }}>{s.source ?? "User input"}</td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        </Card>

        <ChartCard title="Aero map" subtitle="Up and to the left is more efficient. Dashed rays mark equal efficiency C_DF / C_D (labelled)." theme={theme}>
          {(ref) => (
            <XYChart
              svgRef={ref}
              theme={theme}
              height={270}
              xDomain={xDom}
              yDomain={yDom}
              xLabel="Drag coefficient C_D"
              yLabel="Downforce coefficient C_DF"
              xFormat={(v) => fmt(v, 2)}
              yFormat={(v) => fmt(v, 1)}
              tooltipX={(v) => `C_D ${fmt(v, 3)}`}
              tooltipY={(v) => fmt(v, 3)}
              series={isoSeries}
              markers={markers}
              ariaLabel="Drag and downforce coefficients of each setup"
            />
          )}
        </ChartCard>
      </div>

      <div className="grid grid-2">
        <Card
          title="Import CFD force coefficients"
          subtitle="OpenFOAM forceCoeffs (coefficient.dat) or an ANSYS Fluent report file. The converged value is the mean over the final window of iterations."
          actions={<button className="btn btn-sm" onClick={() => { setCfdText(exampleForceCoeffs()); setCols(null); setCfdName("Example (synthetic)"); }}>Load synthetic example</button>}
        >
          <Dropzone onText={(t, name) => { setCfdText(t); setCols(null); setCfdName(name.replace(/\.[^.]+$/, "")); }} label="Drop a force history file here, or click to choose one" accept=".dat,.out,.txt,.csv" />
          {parsed?.error && <div style={{ marginTop: 12 }}><Callout tone="bad" icon={<IconAlert />}>{parsed.error}</Callout></div>}
          {parsed?.h && (
            <div style={{ marginTop: 14, display: "grid", gap: 12 }}>
              <div style={{ display: "flex", gap: 12, flexWrap: "wrap", alignItems: "center" }}>
                <ColumnSelect label="Drag column" value={dragCol} options={Object.keys(parsed.h.columns)} onChange={(v) => setCols({ drag: v, lift: liftCol ?? v })} />
                <ColumnSelect label="Lift column" value={liftCol} options={Object.keys(parsed.h.columns)} onChange={(v) => setCols({ drag: dragCol ?? v, lift: v })} />
                <Segmented
                  label="Lift sign convention"
                  value={liftSign}
                  onChange={setLiftSign}
                  options={[
                    { value: "-1", label: "C_DF = −C_L", title: "Lift positive upward (OpenFOAM and Fluent default)" },
                    { value: "1", label: "C_DF = +C_L", title: "The column already holds downforce" },
                  ]}
                />
              </div>
              <NumberField label="Averaging window" unit="%" value={windowPct} onChange={setWindowPct} min={1} max={100} slider={{ min: 2, max: 50, step: 1 }} hint={`Final ${converged?.samples ?? "–"} of ${parsed.h.index.length} ${parsed.h.indexName.toLowerCase()} samples.`} />
              <ChartCard title="Convergence" theme={theme} className="inset" subtitle="Shaded: averaging window.">
                {(ref) => (
                  <XYChart
                    svgRef={ref}
                    theme={theme}
                    height={200}
                    xDomain={[parsed.h!.index[0]!, parsed.h!.index[parsed.h!.index.length - 1]!]}
                    yDomain={historyY}
                    xLabel={parsed.h!.indexName}
                    yLabel="Coefficient"
                    xFormat={(v) => fmt(v, 0)}
                    yFormat={(v) => fmt(v, 1)}
                    tooltipX={(v) => `${parsed.h!.indexName} ${fmt(v, 0)}`}
                    tooltipY={(v) => fmt(v, 4)}
                    series={historySeries}
                    bands={historyBand ? [{ axis: "x", from: historyBand[0], to: historyBand[1], fill: theme.bandNeutral }] : []}
                    ariaLabel="Force coefficient history"
                  />
                )}
              </ChartCard>
              {converged && (
                <>
                  <dl className="kv">
                    <dt>C_D</dt><dd>{fmt(converged.dragCoefficient, 4)} ± {fmt(converged.dragStd, 4)}</dd>
                    <dt>C_DF</dt><dd>{fmt(converged.downforceCoefficient, 4)} ± {fmt(converged.downforceStd, 4)}</dd>
                    <dt>Drift across the window (C_D, C_DF)</dt><dd>{fmt(converged.dragDrift * 100, 2)} %, {fmt(converged.downforceDrift * 100, 2)} %</dd>
                  </dl>
                  {drifting && <Callout tone="warn" icon={<IconAlert />}>The mean still drifts by more than 1 % across the window. The run may not be converged; check the history before using these values.</Callout>}
                  {parsed.h.metadata.Aref && (
                    <Callout icon={<IconInfo />}>
                      The file reports a reference area of {parsed.h.metadata.Aref} m². Coefficients are only comparable if it matches the vehicle area A = {fmt(state.vehicle.referenceArea, 2)} m².
                    </Callout>
                  )}
                  <div style={{ display: "flex", gap: 8, alignItems: "center" }}>
                    <input className="text-input" value={cfdName} onChange={(e) => setCfdName(e.target.value)} aria-label="Name of the new setup" />
                    <button
                      className="btn btn-primary"
                      disabled={full || converged.downforceCoefficient < 0 || converged.dragCoefficient <= 0}
                      onClick={() => add({ name: cfdName || "CFD case", dragCoefficient: +converged.dragCoefficient.toFixed(5), downforceCoefficient: +converged.downforceCoefficient.toFixed(5), description: "From CFD force history", source: `${parsed.h!.format === "openfoam" ? "OpenFOAM forceCoeffs" : "Fluent report"}, mean of final ${windowPct} %` })}
                    >
                      <IconPlus /> Add as setup
                    </button>
                  </div>
                </>
              )}
            </div>
          )}
        </Card>

        <Card
          title="Wing-angle sweep"
          subtitle="CSV with columns angle_deg, C_D, C_DF from CFD or the wind tunnel. Values between measured angles are interpolated linearly; there is no extrapolation."
          actions={<button className="btn btn-sm" onClick={() => setSweepText(EXAMPLE_SWEEP)}>Load synthetic example</button>}
        >
          <textarea className="code" value={sweepText} onChange={(e) => setSweepText(e.target.value)} placeholder={"angle_deg,C_D,C_DF\n0,0.70,1.90\n10,0.85,3.06\n20,1.22,3.94"} aria-label="Wing sweep CSV" />
          {sweep.error && <div style={{ marginTop: 12 }}><Callout tone="bad" icon={<IconAlert />}>{sweep.error}</Callout></div>}
          {sw && swAt && (
            <div style={{ marginTop: 14, display: "grid", gap: 12 }}>
              <ChartCard
                title="Coefficients against wing angle"
                theme={theme}
                className="inset"
                footer={<Legend items={[{ label: "C_D", colour: theme.components.grip }, { label: "C_DF", colour: theme.ink }, { label: "Selected angle", colour: theme.muted, kind: "dashed" }]} />}
              >
                {(ref) => (
                  <XYChart
                    svgRef={ref}
                    theme={theme}
                    height={200}
                    xDomain={swRange}
                    yDomain={extent([...sw.cd, ...sw.cdf], 0.1, true)}
                    xLabel="Wing angle (deg)"
                    yLabel="Coefficient"
                    xFormat={(v) => fmt(v, 0)}
                    yFormat={(v) => fmt(v, 1)}
                    tooltipX={(v) => `${fmt(v, 1)}°`}
                    tooltipY={(v) => fmt(v, 3)}
                    series={[
                      { id: "cd", label: "C_D", colour: theme.components.grip, points: sw.angles.map((a, i) => [a, sw.cd[i]!] as [number, number]) },
                      { id: "cdf", label: "C_DF", colour: theme.ink, points: sw.angles.map((a, i) => [a, sw.cdf[i]!] as [number, number]) },
                    ]}
                    markers={[
                      ...sw.angles.map((a, i) => ({ x: a, y: sw.cd[i]!, colour: theme.components.grip })),
                      ...sw.angles.map((a, i) => ({ x: a, y: sw.cdf[i]!, colour: theme.ink })),
                    ]}
                    refLines={[{ axis: "x", value: swAngle, colour: theme.muted, dashed: true }]}
                    ariaLabel="Drag and downforce coefficients against wing angle"
                  />
                )}
              </ChartCard>
              <NumberField label="Wing angle" unit="deg" value={swAngle} onChange={setAngle} min={swRange[0]} max={swRange[1]} slider={{ min: swRange[0], max: swRange[1], step: 0.1 }} />
              <dl className="kv">
                <dt>Interpolated C_D</dt><dd>{fmt(swAt.cd, 4)}</dd>
                <dt>Interpolated C_DF</dt><dd>{fmt(swAt.cdf, 4)}</dd>
                <dt>C_DF / C_D</dt><dd>{fmt(swAt.cdf / swAt.cd, 3)}</dd>
              </dl>
              <div>
                <button
                  className="btn btn-primary"
                  disabled={full}
                  onClick={() => add({ name: `Wing ${fmt(swAngle, 1)}°`, dragCoefficient: +swAt.cd.toFixed(5), downforceCoefficient: +swAt.cdf.toFixed(5), description: `Wing angle ${fmt(swAngle, 1)}°`, source: "Interpolated from wing-angle sweep" })}
                >
                  <IconPlus /> Add {fmt(swAngle, 1)}° as setup
                </button>
              </div>
            </div>
          )}
          {full && <div style={{ marginTop: 12 }}><Callout tone="warn" icon={<IconAlert />}>Eight setups is the maximum. Remove one in the sidebar to add another.</Callout></div>}
        </Card>
      </div>
    </div>
  );
}

function ColumnSelect(props: { label: string; value: string | null; options: string[]; onChange: (v: string) => void }) {
  return (
    <label style={{ display: "inline-flex", gap: 8, alignItems: "center", fontSize: 13 }} className="muted">
      {props.label}
      <select className="select" value={props.value ?? ""} onChange={(e) => props.onChange(e.target.value)}>
        {props.options.map((o) => (
          <option key={o} value={o}>{o}</option>
        ))}
      </select>
    </label>
  );
}

export function Dropzone(props: { onText: (text: string, name: string) => void; label: string; accept?: string }) {
  const [over, setOver] = useState(false);
  const id = useMemo(() => `dz-${Math.random().toString(36).slice(2)}`, []);
  const handle = async (f: File | undefined) => f && props.onText(await f.text(), f.name);
  return (
    <label
      htmlFor={id}
      className={`dropzone ${over ? "over" : ""}`}
      onDragOver={(e) => { e.preventDefault(); setOver(true); }}
      onDragLeave={() => setOver(false)}
      onDrop={(e) => { e.preventDefault(); setOver(false); void handle(e.dataTransfer.files[0]); }}
      style={{ display: "block" }}
    >
      {props.label}
      <input id={id} type="file" hidden accept={props.accept} onChange={(e) => { void handle(e.target.files?.[0]); e.target.value = ""; }} />
    </label>
  );
}
